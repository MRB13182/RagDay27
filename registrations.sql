-- 2. SEQUENCE ALLOCATOR & EMPTY DATABASE NUMBER RESET
create or replace function public.get_next_registration_number()
returns table (next_sl_no bigint, next_registration_no text)
language plpgsql
security definer
as $$
declare
  v_count bigint;
  v_max_num bigint := 0;
  v_rec record;
begin
  select count(*) into v_count from public.registrations;
  if v_count = 0 then
    -- Table is completely empty: restart from 1 and RD27-01
    return query select 1::bigint, 'RD27-01'::text;
    return;
  end if;

  -- Table is NOT empty: find the maximum sequence allocated so far without reusing deleted numbers
  for v_rec in select registration_no, sl_no from public.registrations loop
    if v_rec.registration_no ~ '0*([0-9]+)$' then
      v_max_num := greatest(v_max_num, (regexp_matches(v_rec.registration_no, '0*([0-9]+)$'))[1]::bigint);
    end if;
    if v_rec.sl_no is not null then
      v_max_num := greatest(v_max_num, v_rec.sl_no);
    end if;
  end loop;

  v_max_num := v_max_num + 1;
  return query select v_max_num, ('RD27-' || case when v_max_num < 10 then '0' || v_max_num::text else v_max_num::text end);
end;
$$;

-- 3. VERIFY ADMIN PASSCODE
create or replace function public.verify_admin_passcode(p_passcode text)
returns json
language plpgsql
security definer
as $$
declare
  clean_pass text := trim(coalesce(p_passcode, ''));
begin
  if clean_pass = 'nic27.boy' or clean_pass = 'nicboy.27' then
    return json_build_object('role', 'male_admin', 'admin_id', 'male-admin');
  elsif clean_pass = 'nic27.girl' then
    return json_build_object('role', 'female_admin', 'admin_id', 'female-admin');
  else
    return null;
  end if;
end;
$$;

-- 4. GET ADMIN REGISTRATIONS (GENDER-SCOPED DIRECT DATABASE ACCESS)
create or replace function public.get_admin_registrations(p_passcode text)
returns setof public.registrations
language plpgsql
security definer
as $$
declare
  clean_pass text := trim(coalesce(p_passcode, ''));
begin
  if clean_pass = 'nic27.boy' or clean_pass = 'nicboy.27' then
    return query
      select * from public.registrations
      where gender = 'male' and hidden_from_web = false
      order by sl_no desc;
  elsif clean_pass = 'nic27.girl' then
    return query
      select * from public.registrations
      where gender = 'female' and hidden_from_web = false
      order by sl_no desc;
  else
    raise exception 'unauthorized: invalid admin passcode' using errcode = '42501';
  end if;
end;
$$;

-- 5. CREATE REGISTRATION
create or replace function public.create_registration(
  p_full_name text,
  p_class_roll text,
  p_student_id text,
  p_contact_mobile_number text,
  p_academic_group text,
  p_academic_section text,
  p_student_photo text,
  p_send_method text,
  p_sender_mobile_no text,
  p_payment_time text,
  p_transaction_id text,
  p_jersey_back_name text,
  p_jersey_number text,
  p_jersey_size text,
  p_gender text
)
returns public.registrations
language plpgsql
security definer
as $$
declare
  v_next record;
  v_new_reg public.registrations;
begin
  select next_sl_no, next_registration_no into v_next from public.get_next_registration_number();

  insert into public.registrations (
    sl_no,
    registration_no,
    full_name,
    class_roll,
    student_id,
    contact_mobile_number,
    academic_group,
    academic_section,
    student_photo,
    send_method,
    sender_mobile_no,
    payment_time,
    transaction_id,
    jersey_back_name,
    jersey_number,
    jersey_size,
    gender,
    status
  ) overriding system value values (
    v_next.next_sl_no,
    v_next.next_registration_no,
    trim(p_full_name),
    trim(p_class_roll),
    trim(p_student_id),
    trim(p_contact_mobile_number),
    trim(p_academic_group),
    trim(p_academic_section),
    p_student_photo,
    trim(p_send_method),
    trim(p_sender_mobile_no),
    trim(p_payment_time),
    nullif(trim(p_transaction_id), ''),
    trim(p_jersey_back_name),
    trim(p_jersey_number),
    trim(p_jersey_size),
    trim(p_gender),
    'pending'
  ) returning * into v_new_reg;

  return v_new_reg;
end;
$$;

-- 6. APPROVE REGISTRATION
create or replace function public.approve_registration(
  p_passcode text,
  p_registration_no text
)
returns public.registrations
language plpgsql
security definer
as $$
declare
  clean_pass text := trim(coalesce(p_passcode, ''));
  clean_reg_no text := upper(trim(coalesce(p_registration_no, '')));
  v_admin_role text;
  v_admin_id uuid;
  v_reg public.registrations;
begin
  if clean_pass = 'nic27.boy' or clean_pass = 'nicboy.27' then
    v_admin_role := 'male_admin';
  elsif clean_pass = 'nic27.girl' then
    v_admin_role := 'female_admin';
  else
    raise exception 'unauthorized: invalid admin passcode' using errcode = '42501';
  end if;

  select id into v_admin_id from public.admins where role = v_admin_role limit 1;
  if v_admin_id is null then
    v_admin_id := case when v_admin_role = 'male_admin' then '11111111-1111-1111-1111-111111111111'::uuid else '22222222-2222-2222-2222-222222222222'::uuid end;
  end if;

  select * into v_reg from public.registrations where upper(registration_no) = clean_reg_no;
  if not found then
    raise exception 'REGISTRATION_NOT_FOUND' using errcode = 'P0002';
  end if;

  if (v_admin_role = 'male_admin' and v_reg.gender <> 'male') or
     (v_admin_role = 'female_admin' and v_reg.gender <> 'female') then
    raise exception 'GENDER_ROLE_MISMATCH' using errcode = '42501';
  end if;

  update public.registrations
  set status = 'approved',
      approved_by = v_admin_id,
      approved_at = now(),
      reject_reason = null,
      updated_at = now()
  where id = v_reg.id
  returning * into v_reg;

  return v_reg;
end;
$$;

