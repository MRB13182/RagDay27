-- 9. FIND REGISTRATION DUPLICATE
create or replace function public.find_registration_duplicate(
  p_student_id text,
  p_full_name text,
  p_class_roll text,
  p_academic_group text,
  p_academic_section text
)
returns setof public.registrations
language plpgsql
security definer
as $$
begin
  return query
    select * from public.registrations
    where hidden_from_web = false
      and (
        student_id = trim(p_student_id)
        or (lower(trim(full_name)) = lower(trim(p_full_name)) and class_roll = trim(p_class_roll))
      )
    limit 1;
end;
$$;

-- 10. RESUBMIT REJECTED REGISTRATION
create or replace function public.resubmit_rejected_registration(
  p_registration_id uuid,
  p_original_student_id text,
  p_original_full_name text,
  p_original_class_roll text,
  p_original_academic_group text,
  p_original_academic_section text,
  p_full_name text,
  p_class_roll text,
  p_student_id text,
  p_contact_mobile_number text,
  p_academic_group text,
  p_academic_section text,
  p_student_photo text,
  p_send_method text,
  p_sender_mobile_no text,
  p_payment_time text,
  p_transaction_id text,
  p_jersey_back_name text,
  p_jersey_number text,
  p_jersey_size text,
  p_gender text
)
returns public.registrations
language plpgsql
security definer
as $$
declare
  v_reg public.registrations;
begin
  select * into v_reg from public.registrations where id = p_registration_id and status = 'rejected';
