    raise exception 'REJECTED_REGISTRATION_NOT_FOUND' using errcode = 'P0001';
  end if;

  update public.registrations
  set full_name = trim(p_full_name),
      class_roll = trim(p_class_roll),
      student_id = trim(p_student_id),
      contact_mobile_number = trim(p_contact_mobile_number),
      academic_group = trim(p_academic_group),
      academic_section = trim(p_academic_section),
      student_photo = coalesce(p_student_photo, student_photo),
      send_method = trim(p_send_method),
      sender_mobile_no = trim(p_sender_mobile_no),
      payment_time = trim(p_payment_time),
      transaction_id = nullif(trim(p_transaction_id), ''),
      jersey_back_name = trim(p_jersey_back_name),
      jersey_number = trim(p_jersey_number),
      jersey_size = trim(p_jersey_size),
      gender = trim(p_gender),
      status = 'pending',
      reject_reason = null,
      rejected_at = null,
      rejected_by = null,
      updated_at = now()
  where id = p_registration_id
  returning * into v_reg;

  return v_reg;
end;
$$;

-- 11. LOOKUP INVITATION CARD (PUBLIC SAFE RPC)
create or replace function public.lookup_invitation_card(
  p_registration_no text,
  p_student_name text default null
)
returns json
language plpgsql
security definer
as $$
declare
  clean_reg text := upper(trim(coalesce(p_registration_no, '')));
  r record;
begin
  select * into r from public.registrations
  where upper(registration_no) = clean_reg
  limit 1;

  if not found or r.hidden_from_web = true then
    return json_build_object('found', false, 'status', 'hidden_or_not_found', 'can_download', false);
  end if;

  if r.status = 'pending' then
    return json_build_object(
      'found', true,
      'status', 'pending',
      'can_download', false,
      'registration_no', r.registration_no,
      'full_name', r.full_name
    );
  elsif r.status = 'rejected' then
    return json_build_object(
      'found', true,
      'status', 'rejected',
      'can_download', false,
      'registration_no', r.registration_no,
      'full_name', r.full_name,
      'reject_reason', r.reject_reason,
      'rejected_at', r.rejected_at
    );
  else
    return json_build_object(
      'found', true,
      'status', 'approved',
      'can_download', true,
      'id', r.id,
      'sl_no', r.sl_no,
      'registration_no', r.registration_no,
      'full_name', r.full_name,
      'class_roll', r.class_roll,
      'student_id', r.student_id,
      'contact_mobile_number', r.contact_mobile_number,
      'academic_group', r.academic_group,
      'academic_section', r.academic_section,
      'student_photo', r.student_photo,
      'send_method', r.send_method,
      'sender_mobile_no', r.sender_mobile_no,
      'payment_time', r.payment_time,
      'transaction_id', r.transaction_id,
      'jersey_back_name', r.jersey_back_name,
      'jersey_number', r.jersey_number,
      'jersey_size', r.jersey_size,
      'gender', r.gender,
      'approved_at', r.approved_at,
      'created_at', r.created_at,
      'updated_at', r.updated_at
    );
  end if;
end;
$$;

